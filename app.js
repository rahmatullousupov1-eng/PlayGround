function normalizeTestsData() {
    appData.tests = (appData.tests || []).map(test => {
        const meta = getDefaultTestMeta(test.id);
        const fallbackQuestions = generatedQuestionBank[test.id] || [];
        const questions = Array.isArray(test.questions) ? test.questions : fallbackQuestions;
        const normalizedQuestions = questions.map(question => ({
            ...question,
            explanation: question.explanation || buildQuestionExplanation(test, question)
        }));

        return {
            ...test,
            questions: normalizedQuestions,
            questionCount: normalizedQuestions.length,
            difficulty: test.difficulty || 'Средний',
            subjectId: test.subjectId != null ? Number(test.subjectId) : meta.subjectId,
            categoryId: Number(test.categoryId || meta.categoryId),
            isTeacherCreated: Boolean(test.isTeacherCreated),
            updatedAt: test.updatedAt || new Date().toISOString()
        };
    });
}

function buildQuestionExplanation(test, question) {
    const correctAnswer = Array.isArray(question.options) ? question.options[question.correct] : '';
    const testTitle = String(test?.title || '').toLowerCase();
    const questionText = String(question?.text || '').toLowerCase();

    const hintRules = [
        {
            match: () => testTitle.includes('анатом'),
            text: 'Анатомия отвечает за строение тела, органов и систем.'
        },
        {
            match: () => testTitle.includes('физиолог') || questionText.includes('функци'),
            text: 'Физиология объясняет, как органы и системы работают и взаимодействуют.'
        },
        {
            match: () => testTitle.includes('биохим'),
            text: 'Биохимия изучает обмен веществ, молекулы и ферментативные реакции.'
        },
        {
            match: () => testTitle.includes('диагност'),
            text: 'Лучевая диагностика помогает увидеть внутренние структуры и уточнить диагноз.'
        },
        {
            match: () => testTitle.includes('микроб'),
            text: 'Микробиология изучает микроорганизмы, их свойства и роль в инфекции.'
        },
        {
            match: () => testTitle.includes('фармак'),
            text: 'Фармакология связана с действием лекарств, дозировками и безопасностью терапии.'
        },
        {
            match: () => testTitle.includes('инфекц'),
            text: 'Инфекционные болезни вызваны возбудителями и требуют контроля распространения.'
        },
        {
            match: () => testTitle.includes('онколог'),
            text: 'Онкология изучает опухоли, раннюю диагностику и подходы к лечению.'
        },
        {
            match: () => testTitle.includes('интенсив'),
            text: 'Интенсивная терапия нужна при критических состояниях и требует быстрого контроля показателей.'
        }
    ];

    const hint = hintRules.find(rule => rule.match());
    if (hint && correctAnswer) {
        return `Правильный ответ — ${correctAnswer}. ${hint.text}`;
    }

    if (correctAnswer) {
        return `Правильный ответ — ${correctAnswer}. Этот вариант лучше всего соответствует базовому определению по теме "${test.title}".`;
    }

    return `Ответ следует выбирать по базовому определению темы "${test.title}".`;
}

