function getCurrentUserId() {
    if (!appData.user) return '';
    return appData.user.id || appData.user.username || appData.user.email || '';
}

function syncUserPointsFromScoring() {
    if (!appData.user || appData.user.isGuest || typeof scoringModule === 'undefined') {
        return;
    }

    const userId = getCurrentUserId();
    if (!userId) return;

    const points = scoringModule.getUserPoints(userId);
    if (appData.user.progress) {
        appData.user.progress.points = points;
    }
}

function persistCurrentUserState() {
    if (!appData.user) return;

    appData.user = normalizeUserData(appData.user);
    syncUserPointsFromScoring();
    localStorage.setItem('invictusUser', JSON.stringify(appData.user));

    if (!appData.user.isGuest && typeof authenticationModule !== 'undefined' && typeof authenticationModule.syncStoredUser === 'function') {
        authenticationModule.syncStoredUser(appData.user);
    }

    if (typeof scoringModule !== 'undefined' && typeof scoringModule.updateScoreDisplay === 'function') {
        scoringModule.updateScoreDisplay();
    }
}

function enterGuestMode() {
    localStorage.removeItem('invictusUser');

    if (typeof authenticationModule !== 'undefined' && typeof authenticationModule.logout === 'function') {
        authenticationModule.logout();
    } else {
        localStorage.removeItem('currentUser');
    }

    appData.user = createGuestUser();
}

