function splitFullname(fullname) {
    const safeName = (fullname || '').trim();
    if (!safeName) {
        return { lastname: 'Студент', name: '' };
    }

    const parts = safeName.split(/\s+/);
    if (parts.length === 1) {
        return { lastname: parts[0], name: '' };
    }

    return {
        lastname: parts[0],
        name: parts.slice(1).join(' ')
    };
}

