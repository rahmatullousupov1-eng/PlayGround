// Старые ключи прогресса имели вид «курс-предмет-тема». Таблица нужна только для переноса
// уже сохранённого прогресса, закладок и карточек повторения на плоский список предметов.
const LEGACY_SUBJECT_IDS = {"1-1": 1, "1-2": 2, "2-1": 3, "2-2": 4, "3-1": 5, "3-2": 6, "4-1": 7, "4-2": 8, "4-3": 9, "5-1": 10, "5-2": 11, "5-3": 12, "6-1": 13, "6-2": 14, "6-3": 15, "1-3": 16, "1-4": 17, "2-3": 18, "2-4": 19, "3-3": 20, "4-4": 21, "5-4": 22, "6-4": 23};

function migrateLegacyTopicKey(key) {
    // Допускается суффикс после номера темы, например «1-1-0-fc-1» у карточек повторения
    const m = /^(\d+)-(\d+)-(\d+)(-.+)?$/.exec(String(key));
    if (!m) return String(key);
    const subjectId = LEGACY_SUBJECT_IDS[m[1] + '-' + m[2]];
    return subjectId ? `${subjectId}-${m[3]}${m[4] || ''}` : String(key);
}

function migrateLegacySubjectId(subjectId) {
    if (subjectId === null || subjectId === undefined || subjectId === '') return subjectId;
    const m = /^(\d+)-(\d+)$/.exec(String(subjectId));
    if (!m) return subjectId;
    const mapped = LEGACY_SUBJECT_IDS[m[1] + '-' + m[2]];
    return mapped ? String(mapped) : subjectId;
}

// Пересчитать завершённые предметы по фактически пройденным темам.
// Это единственный источник истины после перехода на плоский список предметов.
function recomputeCompletedSubjects(progress, subjects) {
    if (!progress || !Array.isArray(progress.completedTopics) || !subjects) return [];
    const completed = new Set(progress.completedTopics.map(String));
    return Object.entries(subjects).reduce((result, [subjectId, subject]) => {
        const topics = Array.isArray(subject?.topics) ? subject.topics : [];
        if (topics.length && topics.every((_topic, index) => completed.has(`${subjectId}-${index}`))) {
            result.push(String(subjectId));
        }
        return result;
    }, []);
}

function migrateLegacyMediaSubject(item, field) {
    let subject = item[field] !== undefined ? item[field] : (item.subjectId !== undefined ? item.subjectId : item.subject);
    let changed = false;

    if (item.courseId !== undefined && item.courseId !== null && item.subjectId !== undefined && item.subjectId !== null) {
        const legacyKey = `${item.courseId}-${item.subjectId}`;
        if (LEGACY_SUBJECT_IDS[legacyKey]) {
            subject = legacyKey;
            changed = true;
        }
    }

    const migrated = migrateLegacySubjectId(subject);
    if (migrated !== subject) changed = true;
    if ('courseId' in item) {
        delete item.courseId;
        changed = true;
    }
    if ('course' in item) {
        delete item.course;
        changed = true;
    }
    // У видео основное поле — subject, а subjectId остался от старой схемы.
    if (field === 'subject' && 'subjectId' in item) {
        delete item.subjectId;
        changed = true;
    }

    return { subject: migrated, changed };
}

function migrateLegacyVideos() {
    const raw = localStorage.getItem('appVideos');
    if (!raw) return;
    const videos = JSON.parse(raw);
    if (!Array.isArray(videos)) return;

    let changed = false;
    videos.forEach(video => {
        if (!video || typeof video !== 'object') return;
        const subject = migrateLegacyMediaSubject(video, 'subject');
        const topic = video.topic !== undefined ? migrateLegacyTopicKey(video.topic) : video.topic;
        if (subject.changed || subject.subject !== video.subject) {
            video.subject = subject.subject;
            changed = true;
        }
        if (topic !== video.topic) {
            video.topic = topic;
            changed = true;
        }
    });

    if (changed) localStorage.setItem('appVideos', JSON.stringify(videos));
}

function migrateLegacyMedia3d() {
    const raw = localStorage.getItem('app3DModels');
    if (!raw) return;
    const data = JSON.parse(raw);
    if (!data || typeof data !== 'object' || !data.models) return;

    let changed = false;
    Object.values(data.models).forEach(model => {
        if (!model || typeof model !== 'object') return;
        const subject = migrateLegacyMediaSubject(model, 'subjectId');
        const topicId = model.topicId !== undefined ? migrateLegacyTopicKey(model.topicId) : model.topicId;
        if (subject.changed || subject.subject !== model.subjectId) {
            model.subjectId = subject.subject;
            changed = true;
        }
        if (topicId !== model.topicId) {
            model.topicId = topicId;
            changed = true;
        }
    });

    if (changed) localStorage.setItem('app3DModels', JSON.stringify(data));
}

function migrateLegacyStorage() {
    try {
        const bm = JSON.parse(localStorage.getItem('invictus.bookmarks.v1') || '[]');
        if (Array.isArray(bm) && bm.some(k => /^\d+-\d+-\d+$/.test(String(k)))) {
            localStorage.setItem('invictus.bookmarks.v1', JSON.stringify([...new Set(bm.map(migrateLegacyTopicKey))]));
        }
        const srs = JSON.parse(localStorage.getItem('invictus.srs.v1') || '{}');
        if (srs && typeof srs === 'object' && Object.keys(srs).some(k => /^\d+-\d+-\d+(-.+)?$/.test(k))) {
            const next = {};
            Object.entries(srs).forEach(([k, v]) => { next[migrateLegacyTopicKey(k)] = v; });
            localStorage.setItem('invictus.srs.v1', JSON.stringify(next));
        }
        migrateLegacyVideos();
        migrateLegacyMedia3d();
    } catch (e) {
        console.warn('⚠️ Legacy storage migration skipped:', e);
    }
}

