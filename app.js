function initApp() {
    console.log('🚀 Invictus Starting...');
    

    migrateLegacyStorage();

    // Load saved appData from localStorage if exists (for developer mode changes)
    const savedAppData = localStorage.getItem('appData');
    if (savedAppData) {
        try {
            const parsed = JSON.parse(savedAppData);
            // Merge saved data with appData, preserving user data
            // Старый формат с курсами (parsed.courses) больше не поддерживается и игнорируется.
            if (parsed.subjects && typeof parsed.subjects === 'object') appData.subjects = parsed.subjects;
            appData.tests = parsed.tests || appData.tests;
            appData.customScreens = parsed.customScreens || appData.customScreens;
            appData.uiSettings = parsed.uiSettings || appData.uiSettings;
            appData.searchSettings = parsed.searchSettings || appData.searchSettings;
            appData.knowledgeFiles = parsed.knowledgeFiles || appData.knowledgeFiles;
            console.log('✓ Saved app data loaded from localStorage');
        } catch (e) {
            console.warn('⚠️ Failed to load saved appData:', e);
        }
    }
    
    // Initialize preferences early to apply saved theme immediately
    if (typeof preferencesModule !== 'undefined') {
        preferencesModule.init();
    }
    if (typeof InvictusCloud !== 'undefined') InvictusCloud.init();
    if (typeof i18n !== 'undefined') {
        i18n.init();
        i18n.applyToDOM();
    }
    
    // Вставить navbar из template
    const navTemplate = document.getElementById('navbar-template');
    if (navTemplate) {
        const navClone = navTemplate.content.cloneNode(true);
        const navContainer = document.getElementById('navbar-container');
        navContainer.appendChild(navClone);
    }
    
    // Загрузить пользователя из localStorage
    const saved = localStorage.getItem('invictusUser');
    if (saved) {
        try {
            appData.user = JSON.parse(saved);
            console.log(`✓ User loaded: ${appData.user.fullname}`);
        } catch (e) {
            console.warn('⚠️ Failed to parse saved user:', e);
        }
    }

    normalizeAppState();
    applyUiSettings();

    // Initialize the unified knowledge/data layer before navigation.
    if (typeof knowledgeModule !== 'undefined') knowledgeModule.init(appData);

    const authScreen = document.getElementById('auth-screen');
    if (authScreen) {
        authScreen.style.display = 'none';
    }
    
    // Инициализировать критические модули (быстрый старт интерфейса)
    try {
        if (typeof authenticationModule !== 'undefined') authenticationModule.init();
        if (typeof navigationManager !== 'undefined') navigationManager.init(appData);
        if (typeof profileManager !== 'undefined') profileManager.init(appData);
        if (typeof homeModule !== 'undefined') homeModule.init(appData);
        if (typeof settingsModule !== 'undefined') settingsModule.init(appData);
        if (typeof dashboardModule !== 'undefined') dashboardModule.init(appData);
    } catch (e) {
        console.warn('⚠️ Error initializing critical modules:', e);
    }

    console.log('✓ Critical modules initialized — showing UI fast');

    const loading = document.getElementById('loading-screen');
    const revealApp = () => {
        if (loading) loading.style.display = 'none';

        // Initialize navigation-critical modules before first user taps.
        try {
            if (typeof subjectsModule !== 'undefined') subjectsModule.init(appData);
            if (typeof testsModule !== 'undefined') testsModule.init(appData);
            if (typeof progressModule !== 'undefined') progressModule.init(appData);
            if (typeof crosswordModule !== 'undefined') crosswordModule.init(appData);
            if (typeof glossaryModule !== 'undefined') glossaryModule.init(appData);
            if (typeof searchModule !== 'undefined') searchModule.init(appData);
        } catch (e) {
            console.warn('⚠️ Error initializing nav modules:', e);
        }

        const finishInit = () => {
            try {
                if (typeof aiSearchModule !== 'undefined') aiSearchModule.init(appData);
                if (typeof aiSearchUI !== 'undefined') aiSearchUI.init(aiSearchModule);
                if (typeof scoringModule !== 'undefined') scoringModule.init(appData);
                if (typeof scoringUI !== 'undefined') scoringUI.init();
                if (typeof videosModule !== 'undefined') videosModule.init(appData);
                if (typeof mediaLibrary !== 'undefined') mediaLibrary.init();
                if (typeof media3dModule !== 'undefined') media3dModule.init(appData);
                if (typeof media3dUI !== 'undefined') media3dUI.init();

                console.log('✓ All modules initialized (deferred)');
            } catch (err) {
                console.error('❌ Error during deferred init:', err);
            }
        };

        if ('requestIdleCallback' in window) {
            requestIdleCallback(finishInit, {timeout: 1000});
        } else {
            setTimeout(finishInit, 50);
        }

        if ('serviceWorker' in navigator) {
            navigator.serviceWorker.register('/service-worker.js').then(() => {
                console.log('✓ Service Worker registered');
            }).catch((swErr) => {
                console.warn('⚠️ Service Worker registration failed:', swErr);
            });
        }
    };

    if (loading) {
        requestAnimationFrame(() => requestAnimationFrame(revealApp));
    } else {
        revealApp();
    }
    
    // Не показывать регистрацию автоматически
    // Пользователь может зарегистрироваться в настройках (settings)
    if (!appData.user) {
        console.log('ℹ No user found. Guest mode. Redirect to home or settings.');
        appData.user = createGuestUser();
    }
    
    // Показать главный экран
    navigationManager.goTo('home');
    console.log('✓ Invictus Ready!');
}

